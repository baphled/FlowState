#!/bin/sh
# Re-runs `npm ci` unless node_modules was installed from the current
# package-lock.json (stamp: sha256 of the lock, written after a successful ci).
set -eu
stamp=node_modules/.package-lock.sha256
if command -v sha256sum >/dev/null 2>&1; then
  current=$(sha256sum package-lock.json | cut -d' ' -f1)
else
  current=$(shasum -a 256 package-lock.json | cut -d' ' -f1)
fi
if [ -f "$stamp" ] && [ "$(cat "$stamp")" = "$current" ]; then
  exit 0
fi
rm -f -- "$stamp"
npm ci --no-audit --no-fund
printf '%s\n' "$current" > "$stamp"
