package main

import (
	"strings"
	"testing"
)

func TestTypeLayout(t *testing.T) {
	cases := []struct {
		name   string
		path   string
		source string
		want   string
	}{
		{"implementation type", "provider/client.go", "package provider; type Client struct{}", "move type Client"},
		{"alias", "provider/client.go", "package provider; type Name = string", "move type Name"},
		{"owned types", "provider/types.go", "package provider; type Client struct{}; type Port interface{}", ""},
		{"scoped types", "provider/request_types.go", "package provider; type Request struct{}", ""},
		{"related constants", "provider/types.go", "package provider; type State int; const Active State = 1", ""},
		{"function in types", "provider/types.go", "package provider; func New(){}", "functions and methods"},
		{"method in types", "provider/types.go", "package provider; type Client struct{}; func (Client) Run(){}", "functions and methods"},
		{"variable in types", "provider/types.go", "package provider; var Current int", "mutable variables"},
		{"test fixture", "provider/client_test.go", "package provider; type Fake struct{}", ""},
		{"implementation", "provider/client.go", "package provider; func Run(){}", ""},
		{"generated marker is no bypass", "provider/client.go", "// Code generated by fixture. DO NOT EDIT.\npackage provider; type Client struct{}", "move type Client"},
		{"parse error", "provider/client.go", "package provider; type", "parse"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := strings.Join(inspectSource(tc.path, []byte(tc.source)), "\n")
			if tc.want == "" && got != "" {
				t.Fatalf("unexpected finding: %s", got)
			}
			if tc.want != "" && !strings.Contains(got, tc.want) {
				t.Fatalf("finding %q does not contain %q", got, tc.want)
			}
		})
	}
}
